/**
 * 캡션 글자 상한 — **종이에 다 나오는 만큼**이다 (PO 결정 2026-08-18).
 *
 * 정사각 판형(200×200mm)은 칸 높이가 고정이라 캡션이 **두 줄에서 잘린다**.
 * 캡션은 인쇄까지 가는 유일한 사용자 글이라, 반쪽만 남으면 그 사람이 남긴 말이
 * 아니게 된다. 그래서 자르는 대신 **처음부터 두 줄까지만 쓰게** 한다.
 *
 * 계산(가장 좁은 칸 기준 · PrintPages.css 의 사진 영역 174×154):
 *   4장 쪽 칸 폭 = (174 − 거터 6) ÷ 2 = 84mm = 317px
 *   캡션 9pt(12px) · 한글은 1em · 줄 끝이 남는 것을 감안해 92%만 찬다고 본다
 *   한 줄 ≈ 317 × 0.92 ÷ 12 ≈ 24자 → **두 줄 48자**
 *
 * ★ 가장 좁은 칸을 기준으로 잡는다. 1·2장 쪽(174mm)은 두 줄에 100자가 들어가지만,
 *   같은 사진이 어느 쪽에 놓일지는 장수에 따라 달라진다 — 넉넉한 쪽에 맞추면
 *   4장 쪽에서 잘린다.
 * ★ 배치 6종(다음 건)에서 칸 폭이 바뀌면 이 값도 같이 다시 잰다.
 * ★ 화면·서버가 같은 값을 쓴다 — backend/app/models/schemas.py 의
 *   `PhotoCaptionUpdate.caption` · `StoryPayload.text` 와 함께 움직인다.
 */
export const CAPTION_MAX_LENGTH = 48;

/** 상한에 가까워졌을 때만 남은 글자 수를 알린다 — 평소에는 아무 말도 하지 않는다. */
export const CAPTION_HINT_REMAINING = 10;
